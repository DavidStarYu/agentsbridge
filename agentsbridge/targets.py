GENERATED_MARKER = "<!-- generated by agentsbridge; do not edit -->"


def render(target: Target, body: str) -> str:
    """Render the AGENTS.md body for a specific target style."""
    if target.style == "mdc":
        return _render_mdc(body)
    return _render_markdown(body)


def _render_markdown(body: str) -> str:
    lines = [
        GENERATED_MARKER,
        "",
        "> Generated from `AGENTS.md` by [agentsbridge](https://github.com/agentsbridge/agentsbridge).",
        "> Run `agentsbridge sync` after editing `AGENTS.md`. Do not edit this file directly.",
        "",
        body.rstrip(),
        "",
    ]
    return "\n".join(lines)


def _render_mdc(body: str) -> str:
    lines = [
        "---",
        "description: Coding agent rules generated from AGENTS.md by agentsbridge",
        "globs: **/*",
        "alwaysApply: true",
        "---",
        "",
        GENERATED_MARKER,
        "",
        "> Generated from `AGENTS.md` by [agentsbridge](https://github.com/agentsbridge/agentsbridge).",
        "> Run `agentsbridge sync` after editing `AGENTS.md`. Do not edit this file directly.",
        "",
        body.rstrip(),
        "",
    ]
    return "\n".join(lines)

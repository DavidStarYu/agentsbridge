"""Target definitions: how AGENTS.md content maps to each tool's rules file.

A target is a callable-free dataclass describing:
  - name: identifier used on the CLI (--targets claude,copilot)
  - path: file path relative to the project root
  - style: how the body should be rendered (raw markdown, mdc frontmatter, ...)
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Target:
    name: str
    path: str
    style: str = "markdown"  # markdown | mdc
    description: str = ""
    # Some tools nest rules in subdirectories; record parent dirs to create.
    extra_dirs: tuple[str, ...] = field(default_factory=tuple)


